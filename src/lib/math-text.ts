/**
 * خطی که فقط یک فرمول $$…$$ است باید فرمول جدا و وسط‌چین باشد.
 * remark-math فرمول یک‌خطی $$…$$ را درون‌خطی حساب می‌کند و فقط شکل بلوکی
 * ($$ در خط جدا) را جدا نمایش می‌دهد؛ پس خط‌های تک‌فرمولی به شکل بلوکی تبدیل می‌شوند.
 */
export function isolateDisplayMath(text: string) {
  return text.replace(/^[ \t]*\$\$([^\n$][^\n]*?)\$\$[ \t]*$/gm, (_, tex: string) => `\n$$\n${tex.trim()}\n$$\n`);
}
